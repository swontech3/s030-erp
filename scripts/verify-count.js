/**
 * 항목 수 문지기 — **항목이 조용히 사라지는 것을 막는 유일한 장치다.**
 *
 * =============================================================================
 * ★★★ 왜 이것이 있는가 (2026-09-27)
 * =============================================================================
 * `verify-001-003.js` 가 예약 행 하나가 없어서 중간에 죽었고, **뒤 16항목이 안 돌았다.**
 * 그런데 화면에는 「NG 1건」만 보여서 **아무도 몇 달 동안 몰랐다.** 검증이 틀렸다고
 * 말해 주는 것보다 나쁜 것은, 검증이 **덜 돌면서 조용한 것**이다.
 *
 * 그래서 스크립트마다 「몇 항목이 나와야 하는가」를 박아 두고, 끝에서 실제 수와 맞춘다.
 *
 *   모자라면  → **실패**다. 종료코드 1. 항목이 지워졌거나 중간에 죽었다는 뜻이다
 *   늘어나면  → 실패가 아니다. 기대 수를 고치라고 그 자리에서 알려 준다
 *   같으면    → 한 줄로 확인만 찍는다
 *
 * ★★ **보류(hold)도 「돈 것」으로 센다.** 「시험할 조건이 없어 보류」와 「아예 안 돌았다」는
 *    전혀 다른 일이다 — 보류는 사람이 보고 판단할 수 있고, 안 돈 것은 보이지도 않는다.
 *    그러니 세는 것은 `통과 + 실패 + 보류` 다.
 *
 * ★ 기대 수를 **줄여서** 초록을 만들지 않는다. 줄여야 할 상황이면(항목을 일부러 지웠다)
 *   지운 이유를 커밋 메시지에 남긴다. 이 파일은 그 판단을 대신해 주지 않는다.
 */

/**
 * 실제로 돈 항목 수와 기대 수를 맞춘다.
 *
 * @param {object} args
 * @param {number} args.expected 기대 항목 수(스크립트의 `EXPECTED_ITEMS`)
 * @param {number} args.actual   실제로 돈 항목 수 — **보류를 포함한다**
 * @param {string} args.script   스크립트 파일명. 「어디의 EXPECTED 를 고치라」에 쓴다
 * @returns {boolean} 모자라서 **실패**인가. 부르는 쪽이 종료코드에 더한다
 */
function itemCountGate({ expected, actual, script }) {
  const where = script ? `${script} 의 EXPECTED_ITEMS` : 'EXPECTED_ITEMS';

  if (actual === expected) {
    console.log(`항목 수 ${actual}개 — 기대와 같다`);
    return false;
  }

  if (actual > expected) {
    // 실패가 아니다. 항목을 늘린 것은 잘한 일이고, 숫자만 따라오면 된다.
    console.log(
      `※ 항목 수 — ${expected}개를 기대했는데 ${actual}개가 돌았다. ` +
      `항목을 늘렸으면 ${where} 를 ${actual} 로 고친다 (실패는 아니다)`,
    );
    return false;
  }

  console.error(
    `✘ 항목 수 — ${expected}개가 나와야 하는데 ${actual}개만 돌았다 ` +
    `(${expected - actual}개가 사라졌다). 항목이 지워졌거나 중간에 죽었다 — ${where} 를 보라`,
  );
  return true;
}

module.exports = { itemCountGate };
