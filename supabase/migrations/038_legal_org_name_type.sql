-- 비입주사 법무 정보(tb_s080_legal_orgs)에 두 칸을 더한다 — 등기상 상호 · 회사유형.
-- 법인변경 3단계(상세 화면의 기본정보 카드)가 쓴다 (제안 2026-10-10, ★ 적용 전 승인 대기).
--
-- -----------------------------------------------------------------------------
-- ★★ 037 의 「회사명 칸이 없다」를 고치는 것이 아니다
-- -----------------------------------------------------------------------------
-- 037 은 **회사명**(삐용 단체명, 정본은 삐용)을 여기 두지 않기로 했다. 그 결정은 그대로다.
-- 이 칸은 **등기부에 적힌 상호**다 — 법무 서류에 들어가는 이름이고, 삐용 단체명과 다를 수
-- 있다(「㈜에이」 ↔ 「주식회사 에이」). 그리고 삐용 단체 조회가 아직 실연동이 아니라
-- 비입주사의 이름을 ERP 가 읽을 곳이 지금은 없다.
--
--   · 화면의 회사명: 입주사 = ERP 회사명, 비입주사 = 등기상 상호 → 단체코드 → 「단체 {ID}」
--   · 입주사는 이 표를 쓰지 않는다(037 — 복사 금지). 입주사의 등기상 상호는 ERP 회사명이다
--
-- -----------------------------------------------------------------------------
-- 회사유형 — 칸 이름을 tb_s080_companies.member_type 과 맞춘다
-- -----------------------------------------------------------------------------
-- 레거시는 회사유형을 저장하지 않고 **서류를 뽑을 때마다 골랐다**(MEMBER_TYPE 코드,
-- `CorpChangeDocumentsModal`). 입주사는 ERP 에 member_type 이 이미 있으므로, 비입주사도
-- 같은 이름의 칸을 두어 서류를 그리는 코드가 두 출처를 같은 이름으로 읽게 한다(037 의 규칙).
-- 값은 공통코드 MEMBER_TYPE 의 코드값이다(어느 파티션을 쓸지는 결정 대기 — 보고서 참조).
--
-- ★ 두 칸 모두 NULL 허용 · 기본값 없음. 기존 행(0건)에 영향이 없다.
-- =============================================================================

BEGIN;

ALTER TABLE public.tb_s080_legal_orgs
  ADD COLUMN IF NOT EXISTS legal_name  varchar(200),
  ADD COLUMN IF NOT EXISTS member_type varchar(10);

COMMENT ON COLUMN public.tb_s080_legal_orgs.legal_name IS
  '등기상 상호 — 등기부에 적힌 이름. 법무 서류에 들어간다. 삐용 단체명(정본 회사명)과 '
  '다를 수 있다. 비입주사만 — 입주사는 tb_s080_companies.company_name 을 읽는다.';
COMMENT ON COLUMN public.tb_s080_legal_orgs.member_type IS
  '회사유형 — 공통코드 MEMBER_TYPE 코드값. 칸 이름은 tb_s080_companies.member_type 과 같다.';

COMMIT;

