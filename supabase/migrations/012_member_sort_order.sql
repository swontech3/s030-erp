-- 구성원에 **표시 순서** 칸을 더한다. 계약 폼 섹션 3 의 행 순서를 저장할 자리다(3-4 작업 B).
--
-- -----------------------------------------------------------------------------
-- ★★ 왜 필요한가 — created_at 으로는 순서가 안 잡힌다
-- -----------------------------------------------------------------------------
-- `created_at` 의 기본값이 `CURRENT_TIMESTAMP` 이고, 그 값은 **트랜잭션 시작 시각**이다.
-- 명부를 한 번에 저장하면 모든 행의 `created_at` 이 **같은 값**이 되어 정렬이 무너지고,
-- 다음 정렬 키인 `member_id`(UUID)가 순서를 정한다 — 즉 **무작위**다.
--
-- 실제로 2026-09-18 검증에서 「김대표 · 이직원」을 저장했더니 조회에서 「이직원 · 김대표」로
-- 돌아왔다. 섹션 3 은 **1행이 대표자**이고 섹션 1 의 값을 미러링하는 구조라, 순서가 섞이면
-- 화면이 엉뚱한 행을 대표자 자리에 그린다. 저장할 때마다 행이 뒤바뀌는 것도 그 자체로 버그다.
--
-- 값 순서를 화면이 정하고 서버가 그대로 저장한다. 대표자 여부(`is_representative`)와는
-- 별개다 — 대표가 꼭 1행이어야 한다는 규칙은 화면 규칙이고, 이 칸은 **보이는 순서**다.
--
-- ★ 컬럼 1개만 더한다. 테이블을 새로 만들지 않는다.
-- =============================================================================

BEGIN;

ALTER TABLE public.tb_s080_members
  ADD COLUMN IF NOT EXISTS sort_order smallint NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.tb_s080_members.sort_order IS
  '표시 순서(1부터). 계약 폼 섹션 3 의 행 순서다. ★ created_at 은 트랜잭션 시각이라 '
  '한 번에 저장한 행들이 전부 같은 값이 된다 — 정렬에 쓰지 않는다';

COMMIT;

