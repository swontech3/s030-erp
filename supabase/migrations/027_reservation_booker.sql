-- 예약에 **누가 잡았는지 이름**을 남긴다 — `booker_name`.
--
-- =============================================================================
-- ★★ 왜 필요한가 — 예약자 칸이 비어 있었다
-- =============================================================================
-- 시안(`design/handoff/room-booking/03-booking-form.md` §3)의 「예약자 정보」 블록은
-- 조직명 · 예약자 · 연락처 셋을 보여 준다. 우리 예약 행에는 **아무도 기록되지 않았다** —
-- `member_id` 는 항상 NULL 이고 `created_by` 에는 삐용 회원 번호(숫자)만 들어간다.
-- 번호로는 화면에 이름을 띄울 수 없다(삐용 회원 표는 ERP 가 조회하지 못한다 — 003).
--
-- 그래서 **등록 시점의 이름을 그대로 적어 둔다.** 스냅샷이라 나중에 그 사람이 회사를
-- 옮기거나 계정이 사라져도 「누가 잡았는지」가 남는다(계약 이력과 같은 규칙).
--
-- ★ **연락처 칸은 만들지 않았다.** 지금 세션에 전화번호가 없다(삐용 Mock 계정에 필드
--   자체가 없다). 화면은 연락처 자리를 남겨 두고 숨겨 두었으며, 삐용 실연동으로 계정에서
--   받게 되면 그때 이 파일 옆에 `booker_phone` 을 더한다 — 지금 빈 칸을 만들어 두면
--   「있는데 늘 비어 있는 칸」이 되어 아무도 채우지 않는다.
--
-- ★ 이미 들어 있는 예약은 NULL 이다. 화면은 NULL 을 「—」로 그린다.
--
-- 사용: node scripts/apply-migration.js .env supabase/migrations/027_reservation_booker.sql
-- =============================================================================

BEGIN;

ALTER TABLE public.tb_s080_reservations
  ADD COLUMN IF NOT EXISTS booker_name text;

COMMENT ON COLUMN public.tb_s080_reservations.booker_name IS
  '예약을 등록한 사람의 이름 — 등록 시점 스냅샷. 운영자 대행이면 운영자 이름이다. 연락처는 아직 받지 않는다(027 머리말).';

COMMIT;

