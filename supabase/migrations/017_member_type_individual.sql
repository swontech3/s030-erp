-- 017_member_type_individual.sql
--
-- 회원구분에서 **개인사업자와 개인을 가른다.**
--   `P` 개인 → **개인사업자** (이름만 바꾼다. 코드값은 그대로)
--   `Z` 개인 → **신설.** `use_tp='000'` 에만 넣는다
--
-- -----------------------------------------------------------------------------
-- ★★ 왜 — 한 코드가 두 개념을 담고 있었다
-- -----------------------------------------------------------------------------
-- `MEMBER_TYPE 000` 의 `P`(개인) 안에 **사업자등록을 한 개인사업자**와 **하지 않은
-- 개인(프리랜서)**이 함께 있었다. 둘은 서류 요건이 다르다 — 개인사업자는 사업자등록증을
-- 내야 하고, 개인은 아직 없을 수 있다(사업자번호 칸 안내도 「사업자등록 전이면
-- 비워두세요」다).
--
-- 갈라내기 전에는 계약 폼이 이 규칙을 표현할 수 없었다. 016 직후 화면은 「법인이면
-- 사업자등록증 필수」로 두었는데, 그러면 **개인사업자가 사업자등록증 없이 통과한다.**
-- 017 이후로는 시안이 원래 적어 둔 3분법(프리랜서 / 개인사업자 / 법인)이 코드로 표현된다:
--
--     법인      R · A · C · S   법인등록번호 활성 · 법인등기부등본 · 사업자등록증 필수
--     개인사업자 P              법인 칸 없음 · **사업자등록증 필수**
--     개인      Z (신설)        법인 칸 없음 · 사업자등록증 **선택**
--
-- -----------------------------------------------------------------------------
-- ★ `P` 의 **코드값을 바꾸지 않는다.** 이름만 고친다
-- -----------------------------------------------------------------------------
-- 코드값을 바꾸면 그 값을 저장해 둔 기존 데이터가 끊어진다. 지금은 `MEMBER_TYPE` 을
-- 코드로 저장하는 계약이 아직 없지만(§A-2 의 `'개인사업자'` 는 표시명이라 별건이다),
-- 코드값을 손대는 습관을 들이지 않는다 — `ROOM_TP` 의 `R3`(3인실→팀오피스)에서
-- 이미 같은 판단을 했다(`doc/CONTRACT_DATA_MODEL.md` §D ①).
--
-- ★ `Z` 는 `use_tp='000'` **에만** 넣는다. `001`(법인설립용)·`002`(문서양식용)는 법인
--   서류를 만드는 자리라 개인이 들어갈 이유가 없다. 파티션은 독립이므로 한쪽에만
--   넣는 것이 정상이다(`doc/CODE_MASTER_ANALYSIS.md` §B-1).
--
-- ★ `is_system = true` 다. 화면 로직이 `Z` 를 직접 보고 서류 요건을 가른다
--   (`isCorpMemberType`·`needsBizLicense`). 지워지면 그 분기가 죽은 코드가 된다.
-- =============================================================================

BEGIN;

UPDATE public.tb_s080_codes_line
   SET name = '개인사업자',
       updated_at = CURRENT_TIMESTAMP
 WHERE category = 'MEMBER_TYPE' AND use_tp = '000' AND code = 'P';

INSERT INTO public.tb_s080_codes_line
  (line_id, build_id, category, code, name, use_tp, sort_order, is_active, is_system, updated_at)
VALUES ('cl_1_MEMBER_TYPE_Z', '1', 'MEMBER_TYPE', 'Z', '개인', '000', 6, true, true, CURRENT_TIMESTAMP);

COMMIT;

