-- 018_company_member_type_code.sql
--
-- `tb_s080_companies.member_type` 에 들어 있는 **표시명을 코드값으로** 바꾼다.
--   `'개인사업자'` → `'P'`
--
-- -----------------------------------------------------------------------------
-- ★★ 왜 — 이 컬럼만 코드가 아니라 글자를 담고 있었다
-- -----------------------------------------------------------------------------
-- 다른 코드 컬럼은 전부 코드값이다 — `spaces.room_type` 은 `R1`, `contracts.payment_method`
-- 는 `M`. 그런데 `companies.member_type` 에는 **「개인사업자」라는 표시명**이 들어 있었다.
-- 계약 폼이 화면 상수(`MEMBER_TYPES = ['프리랜서','개인사업자','법인']`)로 돌던 시절의
-- 흔적이다. 그 상수는 2026-09-19 에 없어졌다(`MEMBER_TYPE` 코드로 이관).
--
-- 그래서 지금은 **어느 코드와도 맞지 않는다.** 계약 폼이 이 입주사를 열면 회원구분이
-- 빈 칸으로 뜬다 — 화면은 목록에 없는 값을 미선택으로 연다(조용히 첫 값으로 되돌리면
-- 아무 회사나 「주식회사」가 되기 때문이다).
--
-- 017 이 `P` 의 이름을 「개인사업자」로 확정했으므로 **대응 코드가 정확히 있다.**
-- 추측해서 고르는 것이 아니다.
--
-- -----------------------------------------------------------------------------
-- ★ 이름으로 이어 붙인다. 값을 직접 쓰지 않는다
-- -----------------------------------------------------------------------------
-- `SET member_type = 'P'` 한 줄로 끝낼 수도 있지만, **왜 P 인지가 SQL 에 남지 않는다.**
-- 코드 테이블의 이름과 맞는 행만 바꾸게 하면 근거가 문장 안에 있고, 두 번 돌려도
-- 같은 결과다(이미 코드값이 된 행은 이름과 맞지 않아 걸리지 않는다).
--
-- ★ 대상은 `use_tp='000'` 뿐이다. 계약 폼이 보는 파티션이 그것이다.
-- ★ 지금 이 테이블은 **1행**(`MOCK_TENANT_9001` 에스원3DP)이다. 지우지 않는다 —
--   계약 2건 · 구성원 3명이 딸려 있고 **입주사 로그인의 스코프**가 이 회사다.
--   시드 정리는 페이즈 3-2 다. 여기서는 칸 하나를 코드로 맞출 뿐이다.
-- =============================================================================

BEGIN;

UPDATE public.tb_s080_companies c
   SET member_type = l.code,
       updated_at = CURRENT_TIMESTAMP
  FROM public.tb_s080_codes_line l
 WHERE l.category = 'MEMBER_TYPE'
   AND l.use_tp = '000'
   AND l.is_active = true
   AND c.member_type = l.name;

COMMIT;

