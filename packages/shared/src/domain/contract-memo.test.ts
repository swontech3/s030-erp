/**
 * 특기사항의 **자동 줄** — 화면이 얹었다 뺐다 하는 줄과 사람이 쓴 줄을 가른다.
 *
 * ★ 2026-09-21에 `packages/web` 의 `form-model.ts` 에서 옮겨 왔다. 재계약이 특기사항
 *   첫 줄에 문구를 넣게 되면서 **할인 문구와 부딪히는지**를 시험해야 했는데, 두 규칙이
 *   서로 다른 패키지에 있어 함께 걸 수가 없었다(웹에는 시험 러너가 없다).
 *
 * ★ 옮기면서 동작은 바꾸지 않았다. 아래 시험이 그 약속이다.
 */
import { describe, it, expect } from 'vitest';
import { DISCOUNT_PREFIX, discountLabel, withDiscountLine } from './contract-memo.ts';

describe('discountLabel', () => {
  it('기준가보다 싸면 할인 문구', () => {
    expect(discountLabel(100_000, 90_000)).toBe('기준가 대비 -10,000원 (10.0% 할인)');
  });

  it('기준가보다 비싸면 추가 문구', () => {
    expect(discountLabel(100_000, 110_000)).toBe('기준가 대비 +10,000원 (10.0% 추가)');
  });

  it('★ 차액이 없으면 빈 문자열이다 — 없는 할인을 적지 않는다', () => {
    expect(discountLabel(100_000, 100_000)).toBe('');
  });

  it('★ 한쪽이 0 이면 빈 문자열이다 — 아직 안 채운 칸으로 비율을 내지 않는다', () => {
    expect(discountLabel(0, 90_000)).toBe('');
    expect(discountLabel(100_000, 0)).toBe('');
  });

  it('소수 한 자리로 반올림한다', () => {
    expect(discountLabel(300_000, 200_000)).toBe('기준가 대비 -100,000원 (33.3% 할인)');
  });

  /** ★ `withDiscountLine` 이 이 접두사로 자동 줄을 알아본다. 둘이 갈리면 줄이 쌓인다. */
  it('★★ 접두사가 자동 줄의 표식이다', () => {
    expect(discountLabel(100_000, 90_000).startsWith(DISCOUNT_PREFIX)).toBe(true);
  });
});

describe('withDiscountLine', () => {
  /**
   * ★ **옮기면서 고친 한 가지.** 예전에는 빈 특기사항에 얹으면 `"…할인)\n"` 으로
   *   **빈 줄이 하나 붙어** 나왔고(`''.split('\n')` 이 `['']` 이라), 그 값이 그대로
   *   저장되고 계약서에도 실렸다.
   */
  it('★ 빈 특기사항에 얹으면 그 줄만 남는다 — 빈 줄이 붙지 않는다', () => {
    expect(withDiscountLine('', '기준가 대비 -10,000원 (10.0% 할인)')).toBe(
      '기준가 대비 -10,000원 (10.0% 할인)',
    );
  });

  /** ★ 중간의 빈 줄은 사람이 넣은 것일 수 있다 — 떨어뜨리지 않는다. */
  it('★ 사람이 넣은 빈 줄은 보존한다', () => {
    const memo = ['기준가 대비 -10,000원 (10.0% 할인)', '주차 1대 포함', '', '입주일 협의'].join('\n');
    expect(withDiscountLine(memo, '')).toBe(['주차 1대 포함', '', '입주일 협의'].join('\n'));
  });

  /** ★★ 사람이 쓴 줄은 **보존한다.** 자동 줄만 갈아 끼운다. */
  it('★★ 사람이 쓴 줄은 건드리지 않는다', () => {
    const memo = ['기준가 대비 -10,000원 (10.0% 할인)', '주차 1대 포함', '입주일 협의'].join('\n');
    expect(withDiscountLine(memo, '기준가 대비 -20,000원 (20.0% 할인)')).toBe(
      ['기준가 대비 -20,000원 (20.0% 할인)', '주차 1대 포함', '입주일 협의'].join('\n'),
    );
  });

  it('★ 할인이 사라지면 자동 줄만 빠진다', () => {
    const memo = ['기준가 대비 -10,000원 (10.0% 할인)', '주차 1대 포함'].join('\n');
    expect(withDiscountLine(memo, '')).toBe('주차 1대 포함');
  });

  /**
   * ★★★ **첫 줄이 자동 줄이 아니면 밀어낸다 — 지우지 않는다.**
   *    재계약 문구가 첫 줄에 오는 자리라 이것이 깨지면 그 문구가 사라진다.
   */
  it('★★★ 첫 줄이 남의 줄이면 지우지 않고 그 위에 얹는다', () => {
    expect(withDiscountLine('재계약 (이전 계약 기간 2026.01.02 ~ 2027.01.01)', '기준가 대비 -10,000원 (10.0% 할인)')).toBe(
      ['기준가 대비 -10,000원 (10.0% 할인)', '재계약 (이전 계약 기간 2026.01.02 ~ 2027.01.01)'].join('\n'),
    );
  });

  /** ★ 렌더마다 다시 얹히는 자리라, 여러 번 불러도 줄이 쌓이면 안 된다. */
  it('★ 같은 값을 여러 번 얹어도 줄이 쌓이지 않는다', () => {
    const line = '기준가 대비 -10,000원 (10.0% 할인)';
    const once = withDiscountLine('주차 1대 포함', line);
    expect(withDiscountLine(withDiscountLine(once, line), line)).toBe(once);
  });
});
