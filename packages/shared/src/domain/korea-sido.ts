/**
 * 시·도 정식 이름 — 주소의 첫 낱말(줄임말)을 정식 이름으로(10-5, 결정 2026-10-11).
 *
 * 카카오 주소 검색은 도로명 주소를 「서울 강남구 …」처럼 **줄인 시·도**로 준다(`useKakaoPostcode` 가 그대로
 * 저장한다). 법인설립 정관 제3조① · 제4조②의 「서울특별시」 자리는 본점의 시·도 **정식 이름**이어야 해서
 * 이 표로 바꾼다.
 *
 * ★ 표는 이곳 한 곳이다 — 17개 시·도(2024 전북특별자치도 · 2023 강원특별자치도 반영).
 * ★ 표에 없는 첫 낱말은 **그대로** 쓴다(이미 정식 이름 · 옛 이름 「강원도」 등). 값을 지어 넣지 않는다.
 */

/** 줄임말 → 정식 이름(17개). */
export const SIDO_FULL_NAMES: Readonly<Record<string, string>> = {
  서울: '서울특별시',
  부산: '부산광역시',
  대구: '대구광역시',
  인천: '인천광역시',
  광주: '광주광역시',
  대전: '대전광역시',
  울산: '울산광역시',
  세종: '세종특별자치시',
  경기: '경기도',
  강원: '강원특별자치도',
  충북: '충청북도',
  충남: '충청남도',
  전북: '전북특별자치도',
  전남: '전라남도',
  경북: '경상북도',
  경남: '경상남도',
  제주: '제주특별자치도',
};

/** 주소 → 시·도 정식 이름. 첫 낱말이 표에 있으면 정식 이름, 없으면 첫 낱말 그대로, 주소가 비면 ''. */
export function sidoOf(address: string | null | undefined): string {
  const first = (address ?? '').trim().split(/\s+/)[0] ?? '';
  return SIDO_FULL_NAMES[first] ?? first;
}
