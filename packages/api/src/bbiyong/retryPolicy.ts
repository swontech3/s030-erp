/**
 * 삐용 연동 실패를 **언제 다시 보낼지** — 판정 하나뿐인 파일.
 *
 * =============================================================================
 * ★★ 왜 저절로 다시 보내는가
 * =============================================================================
 * 「연동 대기」를 푸는 길이 **운영자가 그 계약 화면을 열어 [다시 시도] 를 누르는 것**
 * 하나뿐이었다. 다른 일 하다 보면 묻히고, 그동안 그 입주사는 삐용에 로그인할 수 없다.
 *
 * =============================================================================
 * ★★★ 멈추는 기준 둘 — **횟수**와 **종류**
 * =============================================================================
 *   ① `retryable === false` 면 **한 번도 다시 보내지 않는다.** 값·권한 문제는 같은
 *      조건으로 보내면 같은 답이 온다(AUTHZ_DENY · 이메일 겹침 · 필수 칸 비었음).
 *      두드려서 풀릴 일이 아니라 **사람이 고쳐야** 하는 일이다.
 *   ② 그 밖에는 **5번**까지. 삐용 장애는 다시 보내면 풀리지만 영원히는 아니다.
 *
 * ★★ ①만으로는 모자란다 — 삐용이 **연락처 중복에 HTTP 500** 을 준다(실측 2026-10-05,
 *    삐용이 고치기로 했다). 500 은 규격 밖이라 ERP 가 장애(`retryable: true`)로 보고,
 *    즉 **영구 실패가 재시도 가능으로 분류된다.** 그걸 받아 주는 것이 ②다. 둘 중
 *    하나만 두면 영원히 두드리는 행이 남는다.
 *
 * =============================================================================
 * 간격 — 뒤로 갈수록 뜸하게 (결정 2026-10-05)
 * =============================================================================
 *     1회 실패 뒤   1분    ← 삐용이 잠깐 끊긴 것은 대개 여기서 풀린다
 *     2회          5분
 *     3회         15분
 *     4회         30분
 *     5회         60분 뒤 마지막 시도 → 실패하면 멈춘다
 *
 * ★ 고정 간격으로 두지 않은 이유: 짧게 고정하면 삐용이 오래 죽어 있을 때 상한을
 *   몇 분 만에 태워 버리고, 길게 고정하면 잠깐 끊긴 것도 한참 뒤에나 풀린다.
 * ★ 최대 지연이 60분인 것은 **그날 안에 끝나게** 하려는 것이다. 합계 약 1시간 50분 —
 *   운영자가 오전에 확정한 계약이면 점심 전에 결론이 난다(풀렸거나 손봐야 한다).
 *
 * =============================================================================
 * ★ 이 파일에는 DB 도 삐용도 없다
 * =============================================================================
 * 「5번인가」, 「값 문제면 멈추는가」, 「아직 기다릴 시각인가」를 **시간만 주입해서**
 * 시험한다. 붙이는 자리는 `companies/retrySweep.ts` 다.
 */

/** 연달아 실패할 수 있는 최대 횟수. 닿으면 화면이 「손봐야 합니다」로 바뀐다. */
export const MAX_LINK_ATTEMPTS = 5;

/**
 * 실패 횟수별 다음 시도까지의 기다림(분). ★ 길이가 `MAX_LINK_ATTEMPTS` 와 같다 —
 * 마지막 칸은 **5번째 시도 전**의 기다림이다.
 */
const BACKOFF_MINUTES = [1, 5, 15, 30, 60] as const;

/** 재시도 판정에 필요한 것 전부. DB 컬럼 이름이 아니라 **뜻**으로 받는다. */
export interface LinkRetryState {
  /** `link_attempt_count` — 연달아 실패한 횟수. */
  attemptCount: number;
  /**
   * `link_retryable` — 마지막 실패가 다시 보내면 풀릴 종류인가.
   * ★ `null` 은 「모른다」다(036 이전 행 등). **막지 않는다** — `false` 만 막는다.
   */
  retryable: boolean | null;
  /** `link_failed_at` — 마지막 실패 시각. 없으면 기다릴 것이 없다. */
  failedAt: Date | null;
}

export type LinkRetryVerdict =
  /** 지금 보낸다. */
  | { kind: 'retry' }
  /** 아직 기다린다. `waitMs` 는 남은 시간(로그·시험용). */
  | { kind: 'wait'; waitMs: number }
  /**
   * 그만둔다 — **사람이 손봐야 한다.** `why` 는 멈춘 이유이고, 화면 문구를 고르는
   * 근거가 아니다(화면은 `link_failed_reason` 을 그대로 보여준다).
   */
  | { kind: 'give_up'; why: 'not_retryable' | 'too_many' };

/**
 * 이 행을 지금 다시 보낼 것인가.
 *
 * ★ 순서가 중요하다 — **종류를 횟수보다 먼저** 본다. 값 문제는 1회 실패만으로도
 *   그만두는 것이 맞고, 횟수를 먼저 보면 「5번은 보내 본다」가 된다.
 */
export function judgeLinkRetry(
  state: LinkRetryState,
  { now = Date.now() }: { now?: number } = {},
): LinkRetryVerdict {
  // ① 값·권한 문제 — 한 번도 다시 보내지 않는다.
  if (state.retryable === false) return { kind: 'give_up', why: 'not_retryable' };

  // ② 횟수 상한.
  if (state.attemptCount >= MAX_LINK_ATTEMPTS) return { kind: 'give_up', why: 'too_many' };

  /*
   * ③ 기다림. 실패 시각을 모르면 **기다리지 않는다** — 실패는 있었는데 시각이 없는
   *   행(손으로 고친 자료)을 영원히 묶어 두지 않는다. 한 번 보내 보면 결론이 난다.
   */
  if (!state.failedAt) return { kind: 'retry' };

  const waitMinutes = BACKOFF_MINUTES[Math.min(state.attemptCount, BACKOFF_MINUTES.length - 1)] ?? 1;
  const readyAt = state.failedAt.getTime() + waitMinutes * 60_000;
  if (readyAt > now) return { kind: 'wait', waitMs: readyAt - now };
  return { kind: 'retry' };
}

/**
 * 화면이 「손봐야 합니다」로 바꿀 상태인가 — **저절로 풀리지 않는다**는 뜻이다.
 *
 * ★ 상태 컬럼을 새로 만들지 않았다. `link_status` 는 그대로 `pending` 이고, 이 판정은
 *   **같은 두 칸에서 유도한다.** 컬럼을 더하면 「pending 인데 manual 인 행」처럼 둘이
 *   어긋나는 상태가 생기고, 어느 날 하나만 고쳐진다(이 저장소가 반복해서 피해 온 모양).
 */
export function needsHumanHand(state: LinkRetryState): boolean {
  return judgeLinkRetry(state).kind === 'give_up';
}
