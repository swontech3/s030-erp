/**
 * 끝난 세션 지우기 — `tb_s080_auth_session` 이 끝없이 자라는 것을 막는다.
 *
 * =============================================================================
 * ★★★ 로그인할 때마다 한 행이 생기고, **2026-10-04 까지 아무도 지우지 않았다**
 * =============================================================================
 * 그날 596행이었고 그중 441행이 끝난 것이었다(만료 349 · 폐기 92). 쌓인 이유는
 * 간단하다 — 지우는 길이 없었다. 그래서 길을 만들되 **사람이 기억해야 도는 길로는
 * 만들지 않는다.** 「따로 돌리는 스크립트」만 두면 지금과 같은 상태가 다시 된다.
 * 서버가 하루 한 번 스스로 돌고(`purgeTimer.ts`), 로그아웃은 그 자리에서 지운다
 * (`store.ts` `revokeSessionByHash`).
 *
 * =============================================================================
 * ★★★ 접속 기록은 **이 표가 아니다.** 운영 전에 제대로 다시 만든다
 * =============================================================================
 * 한때 「세션 행이 유일한 로그인 기록이니 한 달 남기자」고 정했다가 **되돌렸다**
 * (2026-10-04). 이 표로는 알고 싶은 것을 알 수 없기 때문이다:
 *
 *   없다 — 접속 IP · 기기 · **로그인 실패**
 *   있다 — 성공한 로그인의 시각과 회원번호뿐
 *
 * 실패가 없으니 «누가 비밀번호를 두드려 봤나»를 못 보고, IP·기기가 없으니
 * «평소와 다른 데서 들어왔나»도 못 본다. **이 자료로는 해킹 판단을 못 한다.**
 * 못 쓸 기록을 남겨 두면 「기록이 있다」고 착각하게 되는 쪽이 더 나쁘다.
 *
 * ★★ 운영 전에 **접속 기록을 따로 만든다** — 로그인 성공·실패 · 접속 IP · 기기.
 *    그때 **로그인 이력 화면도 함께** 둔다(설정 화면 안).
 *    ★ 그때까지 **이 표를 그 용도로 쓰지 마라.** 여기서 뽑은 수는 근거가 못 된다.
 *
 * =============================================================================
 * ★★ 살아 있는 세션은 **절대** 걸리지 않는다
 * =============================================================================
 * 조건 둘 다 「이미 끝났다」를 본다. 살아 있는 세션은 `expires_at` 이 미래이고
 * `revoked_at` 이 NULL 이라 **어느 쪽도 참이 될 수 없다.** 이 함수가 쓰고 있는
 * 사용자를 끊을 길은 없다.
 */
import { pool } from '../db/pool.ts';

/**
 * 끝난 세션을 지운다 — 만료됐거나 폐기된 것. **유예는 없다.**
 *
 * ★ 기준 시각을 **DB 에서 만든다**(`now()`). 앱에서 계산해 넘기면 앱과 DB 의 시계가
 *   어긋난 만큼 경계가 흔들린다. 지우는 일에 그런 흔들림을 두지 않는다.
 *
 * ★ `revoked_at IS NOT NULL` 도 함께 본다. 지금은 로그아웃이 행을 바로 지우므로
 *   이 조건에 걸릴 행이 평소에는 없다. 그래도 둔다 — DB 에서 직접 폐기한 행
 *   (운영 중 강제 차단 · `verify-2-8` A7)이 영영 남지 않게 하는 자리다.
 *
 * @returns 지운 행 수
 */
export async function purgeDeadSessions(): Promise<number> {
  const { rowCount } = await pool.query(
    `DELETE FROM public.tb_s080_auth_session
      WHERE expires_at <= now() OR revoked_at IS NOT NULL`,
  );
  return rowCount ?? 0;
}
